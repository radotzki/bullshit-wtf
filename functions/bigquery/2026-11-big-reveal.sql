-- NO SCHEMA CHANGE: there is nothing to run in this file. It holds only read-only queries (in
-- comments, like the other files here).
--
-- A game's half follows from its PIN, and every usage row carries the PIN (opened_games.id,
-- closed_games.id, question_results.id, users.pin, forks.origin and forks.forked):
--
--   MOD(TO_CODE_POINTS(SHA256(CONCAT('big-reveal:', UPPER(id))))[OFFSET(0)], 2) = 1
--     TRUE   the staged half: the game had the staged reveal
--     FALSE  the other half: the game kept the reveal as it was
--
-- A PIN is given once, so a PIN is one game. The halves are even: of the 1,556 games opened from
-- 1 August to 12 November 2026, 784 fall in the staged half and 772 in the other.
--
-- What the PIN cannot say: whether the game was in the test at all. A game is in the test only when
-- the phone that made it runs a site that can show the staged reveal. Read from the time the SITE of
-- this change went live (later than the functions) and replace <site release time> with it: before
-- it no game was staged, whatever its PIN. After it, a game made from a tab that was opened before
-- the release and never reloaded plays the reveal as it was even when its PIN falls in the staged
-- half; such games cannot be told apart here. They can only pull the two halves towards each other.
--
-- Test games are left out by their mark (see 2026-11-test-mark.sql).
-- Since 5 Nov every game is logged as closed, so "finished" is not read from closed_games here.

